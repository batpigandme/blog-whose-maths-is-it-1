/**
* make-math-probe.js -- writes math-probe.js, a d8-only file that evaluates the
* inputs of math-cases.txt and reports, per function, how many results have
* d8 14.6.202's bits ("old"), d8 15.4.8's bits ("new"), or neither ("other").
*
*   node v8-sources/make-math-probe.js && d8 v8-sources/math-probe.js
*
* math-probe.js is committed so that a reader can run it without this step;
* running this script again regenerates it byte for byte.
*/
'use strict';
var fs = require( 'fs' );
var lines = fs.readFileSync( __dirname + '/math-cases.txt', 'utf8' ).split( '\n' ).filter( function ( l ) {
	return l && l[ 0 ] !== '#';
});
var src = [
	'// math-probe.js -- generated by make-math-probe.js from math-cases.txt; do not edit.',
	'var CASES = ' + JSON.stringify( lines ) + ';',
	'var F64 = new Float64Array( 1 ); var U32 = new Uint32Array( F64.buffer );',
	'function hex( v ) { F64[ 0 ] = v; return ( "00000000" + U32[ 1 ].toString( 16 ) ).slice( -8 ) + ( "00000000" + U32[ 0 ].toString( 16 ) ).slice( -8 ); }',
	'function num( h ) { U32[ 1 ] = parseInt( h.slice( 0, 8 ), 16 ); U32[ 0 ] = parseInt( h.slice( 8 ), 16 ); return F64[ 0 ]; }',
	'var R = {}; var i; var p; var f; var v; var r;',
	'for ( i = 0; i < CASES.length; i++ ) {',
	'  p = CASES[ i ].split( " " ); f = Math[ p[ 0 ].slice( 5 ) ];',
	'  v = hex( ( p[ 2 ] === "-" ) ? f( num( p[ 1 ] ) ) : f( num( p[ 2 ] ), num( p[ 1 ] ) ) );',
	'  r = R[ p[ 0 ] ] = R[ p[ 0 ] ] || { old: 0, new: 0, other: 0 };',
	'  if ( v === p[ 3 ] ) { r.old += 1; } else if ( v === p[ 4 ] ) { r.new += 1; } else { r.other += 1; }',
	'}',
	'var tot = { old: 0, new: 0, other: 0 }; var k; var s = [];',
	'for ( k in R ) { s.push( k.slice( 5 ) + " " + R[ k ].old + "/" + R[ k ].new + "/" + R[ k ].other ); tot.old += R[ k ].old; tot.new += R[ k ].new; tot.other += R[ k ].other; }',
	'print( "math old/new/other " + tot.old + "/" + tot.new + "/" + tot.other + "  " + s.join( ", " ) );'
];
fs.writeFileSync( __dirname + '/math-probe.js', src.join( '\n' ) + '\n' );
